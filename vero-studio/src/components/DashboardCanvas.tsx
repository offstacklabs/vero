import React from 'react';
import { PinOff, ExternalLink, RefreshCw } from 'lucide-react';
import { MetricCard } from './MetricCard';
import { ChartVisualizer } from './ChartVisualizer';
import { DataTable } from './DataTable';

export interface DashboardTile {
  id: string;
  domain: string;
  title: string;
  tile_type: 'kpi' | 'chart' | 'table';
  chart_type?: string;
  sql?: string;
  data?: {
    columns: string[];
    rows: any[][];
    row_count?: number;
  };
  created_at: string;
}

interface DashboardCanvasProps {
  tiles: DashboardTile[];
  selectedDomain: string;
  onUnpinTile: (tileId: string) => void;
  onOpenInStudio: (sql: string) => void;
  onRefresh: () => void;
  refreshing?: boolean;
}

export const DashboardCanvas: React.FC<DashboardCanvasProps> = ({
  tiles,
  selectedDomain,
  onUnpinTile,
  onOpenInStudio,
  onRefresh,
  refreshing = false
}) => {
  return (
    <div className="dashboard-canvas-container">
      <div className="dashboard-canvas-header">
        <div>
          <h2 style={{ fontSize: '20px', color: 'var(--text-main)', marginBottom: '4px' }}>
            Live Report Canvas [{selectedDomain.toUpperCase()}]
          </h2>
          <p style={{ color: 'var(--text-muted)', fontSize: '13px' }}>
            Pinned analytical KPIs, visualizations, and tables generated by Vero AI.
          </p>
        </div>

        <button 
          className="editor-tool-btn" 
          onClick={onRefresh}
          disabled={refreshing}
          title="Refresh dashboard data"
        >
          <RefreshCw size={13} className={refreshing ? 'spin' : ''} />
          <span>{refreshing ? 'Refreshing...' : 'Refresh'}</span>
        </button>
      </div>

      {tiles.length === 0 ? (
        <div className="dashboard-empty-state">
          <div style={{ fontSize: '36px', marginBottom: '12px' }}>📌</div>
          <div style={{ fontWeight: 600, fontSize: '15px', color: 'var(--text-main)', marginBottom: '6px' }}>
            No Pinned Tiles in {selectedDomain.toUpperCase()} Domain
          </div>
          <div style={{ color: 'var(--text-muted)', fontSize: '13px', maxWidth: '420px', lineHeight: 1.5 }}>
            Click <strong>"Pin to Dashboard"</strong> on any chart, KPI card, or table in Chat or SQL Studio to pin it to this live reporting canvas.
          </div>
        </div>
      ) : (
        <div className="dashboard-grid">
          {tiles.map(tile => (
            <div key={tile.id} className="dashboard-tile-card">
              <div className="dashboard-tile-header">
                <div style={{ display: 'flex', alignItems: 'center', gap: '8px' }}>
                  <span className="dashboard-tile-title">{tile.title}</span>
                  <span className="column-type-badge">{tile.domain}</span>
                </div>

                <div style={{ display: 'flex', alignItems: 'center', gap: '6px' }}>
                  {tile.sql && (
                    <button
                      className="sql-action-btn"
                      onClick={() => onOpenInStudio(tile.sql!)}
                      title="Open and edit query in SQL Studio"
                    >
                      <ExternalLink size={11} />
                    </button>
                  )}
                  <button
                    className="sql-action-btn"
                    onClick={() => onUnpinTile(tile.id)}
                    title="Unpin from dashboard"
                  >
                    <PinOff size={11} color="var(--text-muted)" />
                  </button>
                </div>
              </div>

              <div className="dashboard-tile-body">
                {tile.tile_type === 'kpi' && tile.data && tile.data.rows.length > 0 && (
                  <MetricCard
                    label={tile.data.columns[0] || 'Metric'}
                    value={tile.data.rows[0][0]}
                  />
                )}

                {tile.tile_type === 'chart' && tile.data && (
                  <ChartVisualizer
                    type={tile.chart_type || 'bar'}
                    data={tile.data}
                  />
                )}

                {tile.tile_type === 'table' && tile.data && (
                  <DataTable
                    columns={tile.data.columns}
                    rows={tile.data.rows}
                    tableName={tile.title.toLowerCase().replace(/\s+/g, '_')}
                  />
                )}
              </div>
            </div>
          ))}
        </div>
      )}
    </div>
  );
};
